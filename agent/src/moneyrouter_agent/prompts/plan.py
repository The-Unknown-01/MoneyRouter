# 开场白：不代模型说话，只作为会话的第一条 human 触发的占位语义。
OPENING_USER_TURN = "（请根据现有资料给我一份这个月的资金安排）"


def build_context_block(
    *,
    profile_lines: str,
    cashflow_lines: str,
    briefing_lines: str,
    experience_lines: str,
) -> str:
    """把「机器整理好的资料」拼成一条 system 消息（上下文组装属节点职责）。

    这是给模型看的**事实材料**，不是话术；模型可据此判断与解释，但金额仍以工具为准。
    """
    lines = ["【系统整理好的资料，供你判断与解释；金额以工具结果为准】"]
    lines.append("用户画像：")
    lines.append(profile_lines or "（暂无）")
    lines.append("")
    lines.append("近期收支：")
    lines.append(cashflow_lines or "（暂无）")
    lines.append("")
    lines.append("当前金融环境：")
    lines.append(briefing_lines or "（暂无）")
    if experience_lines:
        lines.append("")
        lines.append("可参考的历史经验（来自以往月度复盘，属于建议性的软提示）：")
        lines.append(experience_lines)
    return "\n".join(lines)


def build_decide_human(*, tool_notes: str, cashflow_lines: str) -> str:
    """把工具计算结果与现金流要点拼成判断节点的输入。"""
    return (
        "【工具计算结果】\n"
        f"{tool_notes or '（本轮没有调用工具；如需具体数字应先调用）'}\n\n"
        "【现金流要点】\n"
        f"{cashflow_lines or '（暂无）'}\n"
    )


def build_adjust_human(*, plan_lines: str, feedback: str) -> str:
    """把当前方案要点与用户反馈拼成调整节点的输入。"""
    return (
        "【当前方案要点】\n"
        f"{plan_lines or '（暂无）'}\n\n"
        "【用户的修改意见】\n"
        f"{feedback or '（无）'}\n"
    )
