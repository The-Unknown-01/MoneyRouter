FINALIZE_SYSTEM = """\
下面是本次访谈中收集到的信息。请把它整理成一份结构化的用户财务画像。

要求：
- profile：规整的基础信息，沿用访谈中确定的字段与口径（例如学生的收入按"每月生活费"，
  并注明口径）。只填访谈中出现过的信息；没提到的一律留空，不要推测、不要套用典型值。
- articulation：一段第三人称的客观描述（如"用户是一名在校大学生……"），**只写结论，
  不写过程**。需要回答的只有：这个人是谁、经济状况如何、攒钱为了什么、多久要用、
  能承受多大波动、投资经验如何、哪些地方需要再解释。通常三五句话说完。
  · 不要描述访谈是怎么进行的：不出现"问过""引导后""最初回答""经…提示后"这类字眼；
  · 不要引用用户的口语原话或个别措辞，也不要对用户的话做点评；
  · 同类细节合并成结论：写"用户投资经验为零、对收益与波动需要通俗解释"，
    不要逐条清点"没买过余额宝、零钱通、基金"；
  · 尚未了解到的项用一句话如实带过（如"家庭负担情况尚未了解"），不要描述打探过程。

结论式写法示例（示范"该写什么"，不是模板，请勿照搬字句）：
- 该这样写：用户对投资与波动不太熟悉，需要更通俗的解释；自评只能接受一两百元的小幅
  波动，也理解收益与亏损都属正常。
- 不要这样写：用户问过"啥意思"，最初说"如果能确保赚回来，中间跌一点也可以"，
  经三档选项引导后表示……（复述了访谈过程与用户原话，是无效信息）

内容只来源于访谈记录，不添加任何未出现的事实。不要给出投资建议，不要承诺收益，
不要推荐具体产品或平台。
"""


def build_finalize_human(transcript: str, understanding_json: str, notes: str) -> str:
    """把访谈记录与当前理解拼成 finalize 节点的输入。"""
    return (
        "【访谈记录】\n"
        f"{transcript or '（无）'}\n\n"
        "【当前结构化理解快照】\n"
        f"{understanding_json or '（空）'}\n\n"
        "【额外了解（要点）】\n"
        f"{notes or '（无）'}\n"
    )
