def build_machine_context(snapshot_json: str, open_probes: str, notes: str) -> str:
    """把"机器记录的当前状态 + 待问关注点"拼成一条 system 消息（供 converse 注入）。

    这是**上下文组装**，属节点职责，不写进 ``MONTH_SYSTEM``。
    """
    lines = ["【机器记录的当前状态，供你更新；不要照抄给用户】"]
    lines.append("本月已知情况：" + (snapshot_json or "（还没有了解到什么）"))
    if notes:
        lines.append("额外了解：" + notes)
    if open_probes:
        lines.append("")
        lines.append(open_probes)
    return "\n".join(lines)


def render_open_probes(probes: list["Probe"]) -> str:
    """把待问关注点渲染成给模型看的线索清单（**由代码生成，模型不该编造**）。"""
    if not probes:
        return ""
    lines = ["【系统给的线索：这些是数据比对得出的、值得向用户追问的点（不要照抄给用户）】"]
    for probe in probes:
        lines.append(f"[{probe.id}] {probe.topic}：{probe.detail}")
    return "\n".join(lines)


