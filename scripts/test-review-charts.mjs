import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const sandbox={window:{}};
vm.runInNewContext(readFileSync(new URL('../web/static/review.js',import.meta.url),'utf8'),sandbox);
const option=sandbox.window.reviewChartOption;
const common={tooltip:{},animation:false};
assert.equal(option('review-comparison',{},common),null);
const summary={period:'2026-09',insights:{schema_version:1,metrics:[{id:'income_cents',current_cents:null,previous_cents:0},{id:'investment_return_cents',current_cents:-100,previous_cents:null}]},diff:{categories:[{category:'餐饮',actual_cents:0,planned_cents:null}]}};
const comparison=option('review-comparison',{review:summary},common);
assert.equal(comparison.series[0].data[0],0);
assert.equal(comparison.series[1].data[0],null);
assert.equal(comparison.series[1].data[1],-1);
const category=option('review-categories',{review:summary},common);
assert.equal(category.series[0].data[0],null);
assert.equal(category.series[1].data[0].value,0);
const history=[{period:'2026-07',snapshot:{coverage_complete:true,income:{role:'actual',amount_cents:10000},balance_cents:2000,investments:{month_return_cents:-100}}},{period:'2026-09',snapshot:{coverage_complete:false,income:{role:'expected',amount_cents:20000},balance_cents:3000,spend_total_cents:0}},{period:'2026-10',snapshot:{income:{role:'actual',amount_cents:99999}}}];
const journey=option('review-history',{review:summary,history},common);
assert.equal(Array.from(journey.xAxis.data).join(','),'2026-07,2026-08,2026-09');
assert.equal(journey.series[0].data[1].value,null);
assert.equal(journey.series[0].data[2].value,null);
assert.equal(journey.series[2].data[2].value,null);
assert.equal(journey.series[1].data[2].value,0);
assert.equal(journey.series[1].data[2].symbol,'emptyCircle');
assert.equal(journey.series[0].connectNulls,false);
const returns=option('review-history',{review:summary,history},common,'returns');
assert.equal(returns.series.length,1);
assert.equal(returns.series[0].data[0].value,-1);
assert.equal(returns.series[0].data[2].value,null);
process.stdout.write('Review charts: nulls, zero, losses, missing months, expected income and trend switching passed.\n');
